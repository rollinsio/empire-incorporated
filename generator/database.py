DOCUMENTS = Table(
    "documents",
    "Registry of every object in the tenant's bucket. sensitivity is the label the document is filed under.",
    "INTERNAL",
    (
        col("document_id", "text"), col("bucket", "text", True), col("object_key", "text", True), col("uri", "text", True),
        col("doc_number", "text", True), col("title", "text", True), col("doc_type", "text", True), col("format", "text", True),
        col("revision", "text", True), col("approval_status", "text", True), col("system_code", "text"), col("program_id", "text"),
        col("author_id", "text", references="employees"), col("approver_id", "text", references="employees"),
        col("created_date", "date", True), col("approved_date", "date"), col("language", "text", True),
        col("supersedes_document_id", "text", references="documents"), col("size_bytes", "integer", True), col("sha256", "text", True),
    ),
    ("document_id",),
)


def document_rows(store: DocumentStore) -> list[dict]:
    by_key = {doc.key: doc.document_id for doc in store.docs}
    return [
        {
            "document_id": doc.document_id, "bucket": store.bucket, "object_key": doc.key, "uri": store.uri(doc),
            "doc_number": doc.doc_number, "title": doc.title, "doc_type": doc.doc_type, "format": doc.fmt,
            "revision": doc.revision, "approval_status": doc.approval_status, "system_code": doc.system_code,
            "program_id": doc.program_id, "author_id": doc.author_id, "approver_id": doc.approver_id,
            "created_date": doc.created_date, "approved_date": doc.approved_date, "language": doc.language,
            "supersedes_document_id": by_key[doc.supersedes_key] if doc.supersedes_key else None,
            "size_bytes": doc.size_bytes, "sha256": doc.sha256, "sensitivity": doc.label,
        }
        for doc in store.docs
    ]
