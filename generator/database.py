"""Postgres schema and seed data: one database per tenant, one schema per database.

A tenant describes each table once, as a ``Table`` spec, and pairs it with its
row dicts. ``write`` turns the pairs into ``schema.sql`` (DDL), ``load.sql``
(``\\copy`` statements in one transaction) and one CSV per table, so the
schema and the seed data cannot drift apart.

Every table gets a ``sensitivity`` column: the row's own ``sensitivity`` value
when it has one, otherwise the table's default.
"""

import csv
import io
from dataclasses import dataclass
from datetime import date, datetime
from pathlib import Path

from generator.docs.model import DocumentStore
from generator.labels import LABELS


@dataclass(frozen=True)
class Column:
    name: str
    sql_type: str
    required: bool = False
    references: str | None = None  # "table" or "table(column)" in the same schema


@dataclass(frozen=True)
class Table:
    name: str
    comment: str
    sensitivity: str
    columns: tuple[Column, ...]
    primary_key: tuple[str, ...]

    def __post_init__(self):
        assert self.sensitivity in LABELS, self.name
        names = [c.name for c in self.columns]
        assert "sensitivity" not in names and len(names) == len(set(names)), self.name
        assert all(key in names for key in self.primary_key), self.name

    @property
    def column_names(self) -> list[str]:
        return [c.name for c in self.columns] + ["sensitivity"]


def col(name: str, sql_type: str, required: bool = False, references: str | None = None) -> Column:
    return Column(name, sql_type, required, references)


def csv_value(value) -> str:
    """How a Python value is written to the seed CSVs (and how ground-truth checks read it back)."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (date, datetime)):
        return value.isoformat()
    return str(value)


def _fk_target(reference: str, schema: str) -> str:
    table, _, column = reference.partition("(")
    return f"{schema}.{table}({column.rstrip(')')})" if column else f"{schema}.{table}"


def schema_sql(schema: str, tables: list[Table]) -> str:
    lines = ["-- Generated by `python -m generator`. Do not edit by hand.", f"CREATE SCHEMA IF NOT EXISTS {schema};", ""]
    for table in tables:
        body = [f"    {c.name} {c.sql_type}{' NOT NULL' if c.required or c.name in table.primary_key else ''}" for c in table.columns]
        body.append("    sensitivity text NOT NULL")
        body.append(f"    PRIMARY KEY ({', '.join(table.primary_key)})")
        lines += [f"CREATE TABLE {schema}.{table.name} (", ",\n".join(body), ");"]
        lines.append(f"COMMENT ON TABLE {schema}.{table.name} IS '{table.comment.replace(chr(39), chr(39) * 2)} Default row sensitivity: {table.sensitivity}.';")
        lines.append("")
    # Foreign keys last, deferrable, so the load order inside one transaction does not matter.
    for table in tables:
        for c in table.columns:
            if c.references:
                lines.append(f"ALTER TABLE {schema}.{table.name} ADD CONSTRAINT {table.name}_{c.name}_fkey "
                             f"FOREIGN KEY ({c.name}) REFERENCES {_fk_target(c.references, schema)} DEFERRABLE INITIALLY DEFERRED;")
    return "\n".join(lines) + "\n"


def load_sql(schema: str, tables: list[Table]) -> str:
    lines = ["-- Generated by `python -m generator`. Run from this directory: psql -f load.sql", "\\set ON_ERROR_STOP on", "BEGIN;"]
    lines += [f"\\copy {schema}.{t.name} ({', '.join(t.column_names)}) FROM '{t.name}.csv' WITH (FORMAT csv, HEADER true)" for t in tables]
    lines += ["COMMIT;", "ANALYZE;"]
    return "\n".join(lines) + "\n"


def table_csv(table: Table, rows: list[dict]) -> bytes:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(table.column_names)
    for row in rows:
        values = [row[c.name] for c in table.columns]
        for c, value in zip(table.columns, values):
            # An unquoted empty CSV field loads as NULL, so required columns must never be empty.
            assert value not in (None, "") or not (c.required or c.name in table.primary_key), (table.name, c.name, row)
        sensitivity = row.get("sensitivity", table.sensitivity)
        assert sensitivity in LABELS, (table.name, sensitivity)
        writer.writerow([csv_value(v) for v in values] + [sensitivity])
    return buffer.getvalue().encode("utf-8")


def write(out_dir: Path, schema: str, tables: list[tuple[Table, list[dict]]]) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    specs = [table for table, _ in tables]
    (out_dir / "schema.sql").write_text(schema_sql(schema, specs), encoding="utf-8")
    (out_dir / "load.sql").write_text(load_sql(schema, specs), encoding="utf-8")
    for table, rows in tables:
        (out_dir / f"{table.name}.csv").write_bytes(table_csv(table, rows))


